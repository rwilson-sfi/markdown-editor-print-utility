    public static ThemeDefinition Get(string? id) =>
        All.FirstOrDefault(theme => string.Equals(theme.Id, id, StringComparison.OrdinalIgnoreCase))
        ?? All[0];

    public static IReadOnlyList<ThemeDefinition> Search(string? query, bool? isDark = null)
    {
        var term = query?.Trim() ?? string.Empty;
        return All.Where(theme =>
                (!isDark.HasValue || theme.IsDark == isDark.Value)
                && (string.IsNullOrEmpty(term)
                    || theme.DisplayName.Contains(term, StringComparison.OrdinalIgnoreCase)
                    || theme.Description.Contains(term, StringComparison.OrdinalIgnoreCase)
                    || theme.Id.Contains(term, StringComparison.OrdinalIgnoreCase)))
            .ToArray();
    }
